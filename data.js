  const OTHER = { key: 'other', title: 'Разное', emoji: '📦' };

  // ------------------------------------------------------------
  // УТИЛИТЫ
  // ------------------------------------------------------------
  function toArray(words) {
    if (!words) return [];
    if (Array.isArray(words)) return words;
    return Object.keys(words);
  }

  // Убираем дубликаты (внутри одного уровня)
  function uniq(arr) {
    const seen = new Set();
    const out = [];
    for (const w of arr) {
      if (!w || seen.has(w)) continue;
      seen.add(w);
      out.push(w);
    }
    return out;
  }

  // Классификатор: возвращает первую подходящую категорию
  function classify(hanzi, ru) {
    const ruL = (ru || '').toLowerCase();
    for (const cat of CATEGORIES) {
      if (cat.exact && cat.exact.indexOf(hanzi) !== -1) return cat.key;
      if (cat.keywords) {
        for (const kw of cat.keywords) {
          if (ruL.indexOf(kw.toLowerCase()) !== -1) return cat.key;
        }
      }
    }
    return 'other';
  }

  // Разбиение массива на куски по N
  function chunk(arr, n) {
    const out = [];
    for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
    return out;
  }

  // ------------------------------------------------------------
  // ПОСТРОЕНИЕ HSK_DATA ДЛЯ ОДНОГО УРОВНЯ
  // ------------------------------------------------------------
  const WORDS_PER_DECK = 30; // размер колоды

  function buildLevel(levelKey) {
    const raw = DICT[levelKey];
    if (!raw) return null;

    // 1. Получаем список слов без повторов
    const allWords = uniq(toArray(raw.words));

    // 2. Собираем карточки
    const cards = [];
    const usedHanzi = new Set(); // защита от повторов на уровне
    for (const hanzi of allWords) {
      if (!hanzi || usedHanzi.has(hanzi)) continue;
      const ru = (raw.ru && raw.ru[hanzi]) || '';
      if (!ru) continue; // без перевода слово бесполезно

      usedHanzi.add(hanzi);
      cards.push({
        hanzi,
        pinyin: (raw.pinyin && raw.pinyin[hanzi]) || '',
        ru:     ru,
        em:     (raw.emoji && raw.emoji[hanzi]) || '📝'
      });
    }

    // 3. Раскладываем по категориям, помечая использованные
    const buckets = {};
    for (const cat of CATEGORIES) buckets[cat.key] = [];
    buckets['other'] = [];

    for (const card of cards) {
      const key = classify(card.hanzi, card.ru);
      buckets[key].push(card);
    }

    // 4. Формируем колоды в порядке категорий
    const decks = [];
    let deckId = 1;

    const ordered = [...CATEGORIES, OTHER];
    for (const cat of ordered) {
      const bucket = buckets[cat.key];
      if (!bucket || !bucket.length) continue;

      const chunks = chunk(bucket, WORDS_PER_DECK);
      chunks.forEach((slice, i) => {
        const title = chunks.length > 1
          ? `${cat.title} ${i + 1}/${chunks.length}`
          : cat.title;

        decks.push({
          id:    deckId++,
          emoji: cat.emoji,
          title: title,
          cls:   'dc' + (((deckId - 1) % 20) + 1),
          words: slice
        });
      });
    }

    return {
      label: (LEVEL_META_LABEL[levelKey] || levelKey),
      decks
    };
  }

