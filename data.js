  function toArray(w) {
    if (!w) return [];
    if (Array.isArray(w)) return w;
    return Object.keys(w);
  }

  function uniq(arr) {
    const seen = new Set();
    const out = [];
    for (const w of arr) {
      if (!w || seen.has(w)) continue;
      seen.add(w);
      out.push(w);
    }
    return out;
  }

  function classify(hanzi, ru) {
    const ruL = (ru || '').toLowerCase();
    for (const cat of CATEGORIES) {
      if (cat.exact && cat.exact.indexOf(hanzi) !== -1) return cat.key;
      if (cat.keywords) {
        for (const kw of cat.keywords) {
          if (ruL.indexOf(kw.toLowerCase()) !== -1) return cat.key;
        }
      }
    }
    return 'other';
  }

  function chunk(arr, n) {
    const out = [];
    for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
    return out;
  }

  // ============================================================
  // СБОРКА HSK_DATA
  // ============================================================
  const WORDS_PER_DECK = 30;

  function buildLevel(levelKey) {
    const raw = HSK_DICT[levelKey];
    if (!raw) return null;

    const allWords = uniq(toArray(raw.words));
    const cards = [];
    const used = new Set();

    for (const hanzi of allWords) {
      if (!hanzi || used.has(hanzi)) continue;
      const ru = (raw.ru && raw.ru[hanzi]) || '';
      if (!ru) continue;
      used.add(hanzi);
      cards.push({
        hanzi,
        pinyin: (raw.pinyin && raw.pinyin[hanzi]) || '',
        ru,
        em: (raw.emoji && raw.emoji[hanzi]) || '📝'
      });
    }

    const buckets = {};
    for (const cat of CATEGORIES) buckets[cat.key] = [];
    buckets['other'] = [];

    for (const card of cards) {
      const key = classify(card.hanzi, card.ru);
      buckets[key].push(card);
    }

    const decks = [];
    let deckId = 1;
    const ordered = [...CATEGORIES, OTHER];

    for (const cat of ordered) {
      const bucket = buckets[cat.key];
      if (!bucket || !bucket.length) continue;

      const chunks = chunk(bucket, WORDS_PER_DECK);
      chunks.forEach((slice, i) => {
        const title = chunks.length > 1
          ? `${cat.title} ${i + 1}/${chunks.length}`
          : cat.title;

        decks.push({
          id: deckId++,
          emoji: cat.emoji,
          title,
          cls: 'dc' + (((deckId - 2) % 20) + 1),
          words: slice
        });
      });
    }

    return { label: (raw.label || levelKey.toUpperCase()), decks };
  }

  const HSK_DATA = {};
  const LEVELS = ['hsk1','hsk2','hsk3','hsk4','hsk5','hsk6'];

  for (const key of LEVELS) {
    if (!HSK_DICT[key]) continue;
    const lvl = buildLevel(key);
    if (lvl && lvl.decks.length) HSK_DATA[key] = lvl;
  }

  window.HSK_DATA = HSK_DATA;

